def main() -> int:
    args = sys.argv[1:]
    mode = "mbt"
    if args and args[0].startswith("--mode="):
        mode = args[0].split("=", 1)[1].strip()
        args = args[1:]

    if len(args) != 2:
        print(
            "Usage: sigmac.py [--mode=mbt|ffi|prove-mbt|prove-mbtp] <input.sigma> <output.mbt|output.mbtp>",
            file=sys.stderr,
        )
        return 1

    in_path = Path(args[0])
    out_path = Path(args[1])
    src = in_path.read_text(encoding="utf-8")
    policies, ciphers = parse_sigma_source(src)

    if mode == "mbt":
        out = emit_aot_mbt(args[0], policies, ciphers)
    elif mode == "ffi":
        out = emit_ffi_mbt(args[0], policies, ciphers)
    elif mode == "prove-mbt":
        out = emit_prove_mbt(args[0], policies, ciphers)
    elif mode == "prove-mbtp":
        out = emit_prove_mbtp(args[0], policies, ciphers)
    else:
        print(f"Unknown mode: {mode}", file=sys.stderr)
        return 1

    out_path.write_text(out, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
